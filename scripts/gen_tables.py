#!/usr/bin/env python3
"""Generate the resampler table the DSP needs (pure Python, no numpy).

Plaits runs at its own frame rate. Its DSP names 48 kHz (kSampleRate), but
the hardware's I2S clock is 72 MHz / 47 / 32 = 47872.34 Hz, and the pitch
constant a0 is computed against THAT rate (plaits/dsp/dsp.h,
kCorrectedSampleRate), so the hardware is in tune at 47872.34 Hz and every
envelope and filter time runs at that rate too. The engine is run here
exactly as the hardware runs it and its output is resampled from
47872.34 Hz to Move's 44.1 kHz.

44100 / (72e6 / 1504) = 6909 / 7500, so every output sample sits at input
time n * 7500/6909, whose fractional part is r/6909. The kernel is a
Kaiser-windowed sinc tabulated at RS_PHASES fractional positions (plus one
guard row); the resampler interpolates linearly between adjacent rows.
Each row is normalised to unity DC gain so DC never becomes a ripple.
"""
import math
import pathlib
import sys


def i0(x):
    """Modified Bessel function of the first kind, order 0 (series)."""
    s, term, k = 1.0, 1.0, 1
    while term > 1e-12 * s:
        term *= (x / (2.0 * k)) ** 2
        s += term
        k += 1
    return s


def kaiser(t, half, beta):
    r = t / half
    if abs(r) > 1.0:
        return 0.0
    return i0(beta * math.sqrt(1.0 - r * r)) / i0(beta)


def sinc(x):
    return 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)


IN_RATE = 72e6 / 1504.0            # 47872.34 Hz: the hardware's frame rate
RS_UP, RS_DOWN = 6909, 7500        # 44100 / IN_RATE, exactly
assert abs(IN_RATE * RS_UP / RS_DOWN - 44100.0) < 1e-6
RS_PHASES = 256                    # tabulated fractional positions
RS_TAPS = 64
RS_HALF = RS_TAPS // 2             # taps k = -31..32 around the output time
RS_CUTOFF_HZ = 22050.0             # -6 dB at Move's Nyquist
RS_BETA = 7.0                      # ~70 dB stopband
fc = RS_CUTOFF_HZ / IN_RATE        # cycles per input sample

rows = []
for p in range(RS_PHASES + 1):
    frac = p / RS_PHASES
    row = []
    for k in range(-RS_HALF + 1, RS_HALF + 1):
        t = frac - k
        row.append(2.0 * fc * sinc(2.0 * fc * t) * kaiser(t, RS_HALF + 0.5, RS_BETA))
    g = sum(row)
    rows.append([v / g for v in row])


def fmt(values, per_line=8):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("  " + ", ".join("%.9ef" % v for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


out = ["/* Generated by scripts/gen_tables.py. Do not edit. */",
       "#pragma once",
       "",
       "#define OPLAITS_RS_UP %d" % RS_UP,
       "#define OPLAITS_RS_DOWN %d" % RS_DOWN,
       "#define OPLAITS_RS_PHASES %d" % RS_PHASES,
       "#define OPLAITS_RS_TAPS %d" % RS_TAPS,
       "#define OPLAITS_RS_HALF %d" % RS_HALF,
       "",
       "/* oplaits_rs_table[p][j]: weight of input sample q + (j - OPLAITS_RS_HALF + 1)",
       " * for the output at input time q + p/OPLAITS_RS_PHASES (row PHASES = guard). */",
       "static const float oplaits_rs_table[OPLAITS_RS_PHASES + 1][OPLAITS_RS_TAPS] = {"]
for row in rows:
    out.append(" {")
    out.append(fmt(row))
    out.append(" },")
out.append("};")
out.append("")

path = pathlib.Path(sys.argv[1])
path.parent.mkdir(parents=True, exist_ok=True)
path.write_text("\n".join(out))
